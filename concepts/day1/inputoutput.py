#input is used to get data from the user. In Python, we can use the input() function to get input from the user. The input() function takes a string as an argument, which is displayed to the user as a prompt.
#output is used to display data to the user. In Python, we can use the print() function to display output to the user. The print() function takes one or more arguments, which are the values that we want to display.

name = input("Enter your name: ") #getting input from the user
#here we are using the input() function to get the user's name and storing it in the variable name.
print("Hello, " + name + "!") #displaying output to the user
